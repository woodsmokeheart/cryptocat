-- Политика для публичного доступа к опубликованным постам
-- Позволяет всем пользователям (включая неаутентифицированных) читать опубликованные посты

CREATE POLICY "Публичный доступ к опубликованным постам" ON posts
  FOR SELECT
  USING (published = true);

-- Если политика уже существует, удаляем её и создаем заново
DROP POLICY IF EXISTS "Публичный доступ к опубликованным постам" ON posts;

CREATE POLICY "Публичный доступ к опубликованным постам" ON posts
  FOR SELECT
  USING (published = true);
